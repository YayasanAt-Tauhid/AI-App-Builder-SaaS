/**
 * mock.ts — Deterministic offline code generator.
 *
 * When no provider API key is configured (or FORCE_MOCK=1), this stands in for
 * a real LLM so the whole product — streaming, parsing, preview, versioning,
 * credits — works end-to-end with zero credentials. It emits the exact strict
 * format real providers are instructed to use, streamed in small chunks with
 * tiny delays so the SSE/typewriter experience is faithful.
 *
 * It inspects the prompt for a few keywords and produces a genuinely runnable
 * React app (a todo app, a counter, or a generic starter), with the heavily
 * commented, beginner-friendly code the product promises.
 */

import type { GenerateOptions, ModelProvider, StreamUsage } from "./provider.js";
import { estimateTokens } from "./provider.js";

function pick(prompt: string): "todo" | "counter" | "starter" {
  const p = prompt.toLowerCase();
  if (/\btodo|task|checklist|to-do\b/.test(p)) return "todo";
  if (/\bcounter|increment|click(er)?\b/.test(p)) return "counter";
  return "starter";
}

