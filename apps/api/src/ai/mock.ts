export class MockProvider implements ModelProvider {
  async *stream(opts: GenerateOptions): AsyncGenerator<string, StreamUsage, void> {
    const output = buildMockOutput(extractPrompt(opts.userMessage));
    // Stream in small chunks to emulate token-by-token delivery.
    const chunkSize = 24;
    for (let i = 0; i < output.length; i += chunkSize) {
      if (opts.signal?.aborted) break;
      yield output.slice(i, i + chunkSize);
      // Small delay so the typewriter effect is visible but generation is quick.
      await sleep(8);
    }
    return {
      inputTokens: estimateTokens(opts.system + opts.userMessage),
      outputTokens: estimateTokens(output),
      providerCacheHit: false,
      engine: "mock",
    };
  }
}

/** Pull the human request back out of the built user message. */
function extractPrompt(userMessage: string): string {
  const m = userMessage.match(/REQUEST:\s*([\s\S]*)$/) || userMessage.match(/^Build this:\s*([\s\S]*)$/);
  return (m?.[1] ?? userMessage).trim();
}

function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms));
}
